namespace DhanService.Models
{
    /// <summary>Market data and scan status returned for the NSE stock-futures universe.</summary>
    public sealed record MarketScannerResponse(
        DateTimeOffset GeneratedAt,
        int InstrumentCount,
        int ScannedCount,
        int FailedCount,
        string? Warning,
        IReadOnlyList<MarketScannerInstrument> Instruments);

    /// <summary>Live and historical indicator values for one stock-futures contract.</summary>
    public sealed record MarketScannerInstrument(
        string SecurityId,
        string TradingSymbol,
        string UnderlyingSymbol,
        DateTimeOffset LastUpdated,
        decimal LastPrice,
        decimal Vwap,
        decimal Ema20,
        decimal Ema50,
        decimal Rsi14,
        decimal MacdHistogram,
        decimal Atr14,
        decimal SessionVolume,
        decimal AverageVolume,
        decimal PreviousHigh,
        decimal PreviousLow,
        int HistorySessions,
        decimal? RelativeStrengthPercent,
        decimal AverageDailyTurnover,
        decimal LongRiskReward,
        decimal ShortRiskReward,
        bool IsLiquid,
        bool LongMarketTrend,
        bool ShortMarketTrend,
        bool LongRelativeStrength,
        bool ShortRelativeStrength,
        bool LongEmaAlignment,
        bool ShortEmaAlignment,
        bool LongAboveVwap,
        bool ShortBelowVwap,
        bool LongAboveEma20,
        bool ShortBelowEma20,
        bool LongAboveEma50,
        bool ShortBelowEma50,
        bool LongRsiConfirmation,
        bool ShortRsiConfirmation,
        bool VolumeConfirmation,
        bool LongBreakout,
        bool ShortBreakdown,
        bool LongPullbackConfirmation,
        bool ShortPullbackConfirmation,
        decimal LongEntryTrigger,
        decimal ShortEntryTrigger,
        decimal LongStopLoss,
        decimal ShortStopLoss,
        decimal LongTarget,
        decimal ShortTarget,
        bool LongMacdConfirmation,
        bool ShortMacdConfirmation);
}
